package com.prof18.klead.internal.extractors.site

import com.fleeksoft.ksoup.Ksoup
import com.fleeksoft.ksoup.nodes.Document
import com.prof18.klead.RemovalRecord
import com.prof18.klead.internal.extractors.createExtractorContext
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue

class FramerProfileTest {
    @Test
    fun `matches pages generated by Framer only`() {
        assertTrue(FramerProfile.matches(context(framerPage(collectionItem = true))))
        val wordPress = Ksoup.parse("""<meta name="generator" content="WordPress 6.8"><p class="hidden-m1">Text</p>""")
        assertFalse(FramerProfile.matches(context(wordPress)))
    }

    @Test
    fun `keeps only the blocks the narrowest breakpoint shows`() {
        val document = framerPage(collectionItem = true)

        FramerProfile.preProcess(document.body(), context(document))

        assertNull(document.selectFirst("#desktop-related"))
        assertNull(document.selectFirst("#separator"))
        assertNotNull(document.selectFirst("#mobile-related"))
        assertNotNull(document.selectFirst("#cover"))
    }

    @Test
    fun `removes the label before the title and the blocks after the article body`() {
        val document = framerPage(collectionItem = true)
        val debug = mutableListOf<RemovalRecord>()

        FramerProfile.postProcess(document.body(), context(document), debug)

        assertNull(document.selectFirst("#back-link"))
        assertNull(document.selectFirst("#related"))
        assertNull(document.selectFirst("#newsletter"))
        assertNotNull(document.selectFirst("h1"))
        assertNotNull(document.selectFirst("#byline"))
        assertNotNull(document.selectFirst("#cover"))
        assertEquals(3, document.select("#body p").size)
        assertEquals(3, debug.size)
    }

    @Test
    fun `keeps every section of a page that is not a CMS item`() {
        val document = framerPage(collectionItem = false)
        val debug = mutableListOf<RemovalRecord>()

        FramerProfile.postProcess(document.body(), context(document), debug)

        assertNotNull(document.selectFirst("#back-link"))
        assertNotNull(document.selectFirst("#related"))
        assertNotNull(document.selectFirst("#newsletter"))
        assertTrue(debug.isEmpty())
    }

    private fun context(document: Document) = createExtractorContext(URL, "example.com", document)

    private fun framerPage(collectionItem: Boolean): Document {
        val collectionItemId = if (collectionItem) ""","collectionItemId":"abc123"""" else ""
        val hydration = """{"routeId":"r1","breakpoints":[""" +
            """{"hash":"d1","mediaQuery":"(min-width: 1200px)"},""" +
            """{"hash":"t1","mediaQuery":"(min-width: 810px) and (max-width: 1199.98px)"},""" +
            """{"hash":"m1","mediaQuery":"(max-width: 809.98px)"}]$collectionItemId}"""
        val paragraph = "Text messages reach people on a device they trust, at a moment they are not on guard. "
        return Ksoup.parse(
            """
                <html><head><meta name="generator" content="Framer dda35a3"></head><body>
                <div id="main" data-framer-hydrate-v2='$hydration'>
                  <div id="page">
                    <div id="header">
                      <a id="back-link" href="../blog"><div $RICH_TEXT><p>Blog</p></div></a>
                      <div $RICH_TEXT><h1>Why SMS attacks work</h1></div>
                      <div id="byline">
                        <div $RICH_TEXT><p>Ada Lovelace</p></div>
                        <div id="separator" class="hidden-m1" $RICH_TEXT><p>·</p></div>
                      </div>
                    </div>
                    <div id="cover" class="ssr-variant"><img src="/cover.png" alt="Cover"></div>
                    <div id="body" $RICH_TEXT>
                      <p>${paragraph.repeat(2)}</p><h2>Speed over inspection</h2><p>${paragraph.repeat(2)}</p>
                      <p>${paragraph.repeat(2)}</p>
                    </div>
                    <div id="related">
                      <div $RICH_TEXT><h3>Recent posts</h3></div>
                      <div id="desktop-related" class="ssr-variant hidden-m1"><a href="./other"><p>Other post</p></a></div>
                      <div id="mobile-related" class="ssr-variant hidden-d1 hidden-t1"><a href="./other"><p>Other post</p></a></div>
                    </div>
                  </div>
                  <div id="newsletter"><div $RICH_TEXT><p>Get new posts delivered to your inbox.</p></div></div>
                </div>
                </body></html>
            """.trimIndent(),
            URL,
        )
    }

    private companion object {
        const val URL = "https://example.com/blog/why-sms-attacks-work"
        const val RICH_TEXT = """data-framer-component-type="RichTextContainer""""
    }
}
